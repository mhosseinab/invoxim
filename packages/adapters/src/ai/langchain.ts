import { CallbackManager } from "@langchain/core/callbacks/manager";
import { HumanMessage, SystemMessage } from "@langchain/core/messages";
import { ChatOpenAICompletions } from "@langchain/openai";

/**
 * LangChain normally installs callbacks from ambient environment/async context.
 * This adapter uses only our separately gated, redacted LangSmith exporter.
 * Pin/test this public callback-manager seam when upgrading LangChain.
 */
class PrivateCallbacks extends CallbackManager {
  override addHandler(): void {
    // Deliberately reject inherited, ambient tracing and console handlers.
  }
  override copy(): CallbackManager {
    return new PrivateCallbacks();
  }
}

/** Public ChatOpenAICompletions invocation with a code-owned, bounded HTTP transport. */
export async function invokeChatModel(options: {
  body: string;
  endpoint: string;
  key: string;
  signal: AbortSignal;
  timeoutMs: number;
  transport: () => Promise<Response>;
}) {
  // The body is generated by requestBody(), never parsed from provider input.
  const request: {
    model: string;
    messages: [{ content: string }, { content: string }];
  } = JSON.parse(options.body);
  const origin = new URL(options.endpoint).origin;
  const callbacks = new PrivateCallbacks();
  const model = new ChatOpenAICompletions({
    model: request.model,
    apiKey: options.key,
    maxRetries: 0,
    timeout: options.timeoutMs,
    streaming: false,
    streamUsage: false,
    cache: false,
    verbose: false,
    outputVersion: "v0",
    callbacks,
    configuration: {
      baseURL: origin,
      maxRetries: 0,
      logLevel: "off",
      fetch: async (url, init) => {
        if (
          String(url) !== `${origin}/chat/completions` ||
          init?.method !== "POST" ||
          options.signal.aborted
        )
          throw new Error("AI transport unavailable");
        // The approved body owns schema, exact model/token fields and reservation.
        // SDK defaults/model-name heuristics cannot change that wire contract.
        return options.transport();
      },
    },
  });
  return model.invoke(
    [
      new SystemMessage(request.messages[0].content),
      new HumanMessage(request.messages[1].content),
    ],
    { signal: options.signal, callbacks, maxRetries: 0 },
  );
}
